/**
 * 배포 게이트 목록 생성기.
 *
 * `src/shared/config/envRegistry.ts`에서 SSM으로 받는 키만 뽑아 `infra/aws/env-gate.txt`를 쓴다.
 * 배포 잡은 Node 도구 없이 `check-env.sh`(bash)로 돌기 때문에, 레지스트리를 직접 읽지 않고
 * 커밋된 텍스트 파일을 읽는다. 그 파일이 레지스트리와 같은지는 가드
 * (`src/__tests__/guards/envRegistry.test.ts`)가 확인한다.
 *
 * `yarn env:gate`로 재생성한다.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ENV_REGISTRY, type EnvSpec } from '@/shared/config/envRegistry';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
export const ENV_GATE_OUTPUT = join(SCRIPT_DIR, '../infra/aws/env-gate.txt');

export const ENV_GATE_HEADER =
    '# generated by yarn env:gate from src/shared/config/envRegistry.ts; do not edit';

/** `required KEY` / `optional KEY` / `override KEY` 한 줄씩, SSM 키만, 이름순. 끝에 개행. */
export function renderEnvGate(registry: readonly EnvSpec[]): string {
    const lines = registry
        .filter(spec => spec.sources.includes('ssm'))
        .toSorted((a, b) => (a.name < b.name ? -1 : 1))
        .map(spec => `${spec.requirement} ${spec.name}`);
    return `${[ENV_GATE_HEADER, ...lines].join('\n')}\n`;
}

const executedDirectly =
    process.argv[1] !== undefined &&
    fileURLToPath(import.meta.url) === process.argv[1];

if (executedDirectly) {
    const source = renderEnvGate(ENV_REGISTRY);
    writeFileSync(ENV_GATE_OUTPUT, source);
    console.log(
        `[env:gate] ${source.split('\n').length - 2} keys → ${ENV_GATE_OUTPUT}`
    );
}
