/**
 * 대상 언어 이름. 한국어 본문 안의 한 줄짜리 지시다.
 *
 * ⚠️ **이 줄만으로는 비-ko에서 동작하지 않는다.** 실측에서 ja·zh는 3/3 모두
 * 한국어로 나왔다 — 모델이 프롬프트 자체의 언어를 본보기로 삼기 때문이다.
 * 실효적인 지시는 프롬프트 맨 끝의 {@link plainOutputLanguageDirective}이고,
 * 이 줄은 ko 프롬프트의 바이트를 유지하기 위해 남겨 둔다.
 */
const LOCALE_NAME: Record<string, string> = {
    ko: '한국어',
    en: '영어(미국)',
    ja: '일본어',
    zh: '중국어 간체',
};

export interface BuildPlainPromptInput {
    /** 대체 경로가 제거된 산문 조각. */
    readonly entries: readonly ProseEntry[];
    readonly facts: PlainFacts;
    readonly locale: string;
    /** 재시도일 때만. 직전 실패를 지적하는 문구가 프롬프트 끝에 붙는다. */
    readonly retryHint?: string;
}

/**
 * 입력을 `prose`(경로 → 문장 맵)와 `facts` 두 덩이로 준다.
 *
 * 경로 키가 의미를 실어주므로(어느 값이 요약이고 어느 값이 지지선 근거인지)
 * 타입별 프롬프트 분기가 필요 없다. 7종 분석이 같은 프롬프트를 탄다.
 */
export function buildPlainPrompt({
    entries,
    facts,
    locale,
    retryHint,
}: BuildPlainPromptInput): string {
    const prose = Object.fromEntries(
        entries.map(entry => [entry.path, entry.text])
    );
    const language = LOCALE_NAME[locale] ?? LOCALE_NAME.ko;

    return `${plainOutputLanguageHeader(locale)}당신은 주식 분석 결과를 투자 초보자가 읽을 수 있게 다시 쓰는 편집자입니다.

아래 \`prose\`는 하나의 전문가용 분석문을 조각낸 것이고, 키는 그 조각이 원래 있던 위치입니다.

${PLAIN_RULES}
- ${language}로 쓰세요.
- 완성된 글만 출력하세요. 인사말, 설명, 따옴표, 코드블록을 붙이지 마세요.
  문단 사이는 빈 줄로 구분합니다.
${retryHint ? `\n${retryHint}\n` : ''}
prose:
${JSON.stringify(prose, null, 1)}

facts:
${JSON.stringify(facts)}${plainOutputLanguageDirective(locale)}`;
}
