import type { ProseEntry } from '@/entities/analysis-translation';
import type { PlainFacts } from './collectFacts';

/**
 * 평이화 프롬프트 버전. `PLAIN_RULES`를 고치면 반드시 올린다 — 캐시 키에 들어가므로
 * 올리지 않으면 TTL 30일 동안 예전 문장이 그대로 나온다.
 */
export const PLAIN_PROMPT_VERSION = 'v2';

/**
 * 재작성 규칙.
 *
 * ## 왜 지표 이름을 한 개도 적지 않는가
 *
 * `skills/**` 에 스킬이 82개 있고 거기서 파생되는 지표·전략·패턴 이름이 108개다.
 * 프롬프트에 열거하면 스킬이 추가될 때마다 목록이 뒤처지고, 뒤처진 이름은 그대로
 * 화면에 새어 나간다. 게다가 실측에서 **목록은 효과가 없었다** — 금지어 27개를
 * 넣고 빼는 2×2 실험에서 전문 용어 잔존이 2.50 → 2.25(노이즈)였다.
 *
 * 대신 "이름"이라는 **카테고리 자체**를 금지한다. 스킬이 200개가 되어도 유효하다.
 *
 * ## 왜 글자 수·문단 수를 제한하지 않는가
 *
 * 분석 타입마다 적정 분량이 다르다(실측 압축률: technical 37%, news 105%).
 * 고정 숫자는 특정 타입에 맞춘 상수이고, 실제로 지시해도 지켜지지 않았다.
 *
 * ## 마지막 두 규칙이 핵심이다
 *
 * 이름만 금지하면 모델은 영어 약어를 한자어로 갈아치우고 끝낸다. `ROE`가
 * `자기자본이익률`이 되면 기계 지표는 만점이지만 비전문가에게는 똑같이 모르는
 * 말이다. 실측에서 `fundamental` 출력이 정확히 그랬다(압축률 91% — 사실상 1:1 번역).
 * "옮기는 것만으로 부족하다" + "항목을 차례대로 옮기지 마라"를 넣자 같은 입력의
 * 숫자 밀도가 10.1 → 0.9로, 압축률이 91% → 56%로 떨어졌다.
 *
 * 그리고 `technical`은 같은 규칙에서 숫자 밀도가 오히려 올라갔다(10.0 → 11.1) —
 * 지지선·저항선은 독자가 알아야 할 값이기 때문이다. **타입별 분기 없이 모델이
 * 스스로 조절한다.**
 */
const PLAIN_RULES = `과한 어휘 없이, 과한 문장 없이, 읽기 쉽게, 편하게,
자연어·문어체 기반으로 사람이 읽기 쉬운 흐름으로 다시 써주세요.

- 지표, 전략, 패턴, 기법에 붙은 고유한 이름은 쓰지 마세요.
  영어 약어, 사람 이름에서 온 용어, 도형이나 사물에 빗댄 이름이 모두 여기 해당합니다.
  이름을 지우고, 그 이름이 가리키는 현상 자체를 우리말로 쓰세요.
  원본이 "무엇을 근거로" 판단했는지가 아니라 "무엇이 벌어지고 있는지"를 쓰는 것입니다.
- 읽는 사람은 주식 용어를 전혀 모릅니다. 설명 없이 등장하는 단어가
  하나라도 있으면 그 사람은 거기서 읽기를 멈춥니다.
- 이름을 우리말로 옮기는 것만으로는 부족합니다. 옮긴 말도 처음 듣는 사람에게는
  여전히 모르는 말입니다. 수치를 그대로 옮겨 적지 말고, 그 수치가 이 회사의 무엇을
  말해 주는지, 좋은 쪽인지 나쁜 쪽인지를 함께 쓰세요.
  독자가 궁금한 것은 "이 값이 얼마인가"가 아니라 "그래서 어떻다는 것인가"입니다.
- 원본의 항목을 하나씩 차례대로 옮기지 마세요. 원본이 여러 항목으로 나눠 말한 것을
  하나의 이야기로 엮어, 중요한 것부터 자연스럽게 이어 쓰세요.
- prose와 facts에 없는 숫자를 만들지 마세요. 퍼센트를 직접 계산하지 마세요.
- 원본에 있는 가격은 자릿수를 바꾸지 말고 그대로 옮기세요.
- 가격을 쓸 때는 반드시 facts.currency에 적힌 단위를 붙이세요. 단위 없는 숫자만
  적으면 읽는 사람은 그 값이 무엇인지 알 수 없습니다.
- 매수, 매도를 권유하는 단정적 표현을 쓰지 마세요.
- 마크다운, 불릿, 제목, 이모지를 쓰지 마세요. 문단으로만 씁니다.`;

/** 대상 언어 이름. 프롬프트가 출력 언어를 지정한다. */
const LOCALE_NAME: Record<string, string> = {
    ko: '한국어',
    en: '영어(미국)',
    ja: '일본어',
    zh: '중국어 간체',
};

export interface BuildPlainPromptInput {
    /** 대체 경로가 제거된 산문 조각. */
    readonly entries: readonly ProseEntry[];
    readonly facts: PlainFacts;
    readonly locale: string;
    /** 재시도일 때만. 직전 실패를 지적하는 문구가 프롬프트 끝에 붙는다. */
    readonly retryHint?: string;
}

/**
 * 입력을 `prose`(경로 → 문장 맵)와 `facts` 두 덩이로 준다.
 *
 * 경로 키가 의미를 실어주므로(어느 값이 요약이고 어느 값이 지지선 근거인지)
 * 타입별 프롬프트 분기가 필요 없다. 7종 분석이 같은 프롬프트를 탄다.
 */
export function buildPlainPrompt({
    entries,
    facts,
    locale,
    retryHint,
}: BuildPlainPromptInput): string {
    const prose = Object.fromEntries(
        entries.map(entry => [entry.path, entry.text])
    );
    const language = LOCALE_NAME[locale] ?? LOCALE_NAME.ko;

    return `당신은 주식 분석 결과를 투자 초보자가 읽을 수 있게 다시 쓰는 편집자입니다.

아래 \`prose\`는 하나의 전문가용 분석문을 조각낸 것이고, 키는 그 조각이 원래 있던 위치입니다.

${PLAIN_RULES}
- ${language}로 쓰세요.
- 완성된 글만 출력하세요. 인사말, 설명, 따옴표, 코드블록을 붙이지 마세요.
  문단 사이는 빈 줄로 구분합니다.
${retryHint ? `\n${retryHint}\n` : ''}
prose:
${JSON.stringify(prose, null, 1)}

facts:
${JSON.stringify(facts)}`;
}
