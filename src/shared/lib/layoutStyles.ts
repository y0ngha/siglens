/**
 * 페이지 폭 규약.
 *
 * 리디자인 전에는 `lg:px-[15vw]` / `lg:pr-[10vw]`가 13개 파일 21곳에 흩어져
 * 있었고 `max-width`가 아예 없었다. 뷰포트 비율 패딩만으로 폭을 잡으면
 * 2560px 화면에서 좌우로 384px씩 버려지는데도 본문 줄 길이는 계속 늘어나
 * 읽기가 힘들어진다. 반대로 1280px에서는 여백이 부족해진다.
 *
 * 고정 최대폭 + 고정 거터로 바꾼다. 데이터 밀도가 높은 제품이라 본문 폭은
 * 넉넉히 두되(1200px), 그 위로는 늘리지 않는다.
 *
 * 컴포넌트가 아니라 문자열 상수인 이유는 `surfaceStyles`와 같다 — 21곳을
 * 래퍼 컴포넌트로 감싸면 DOM 깊이가 바뀌어 E2E 로케이터와 SEO 텍스트 위치에
 * 회귀 위험이 생긴다. 클래스만 갈아끼우면 구조는 그대로다.
 *
 * 차트 페이지(`/[symbol]`)는 예외다 — 전체 폭을 써야 캔들이 충분히 보인다.
 */
